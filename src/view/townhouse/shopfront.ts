import { VoxelMeshBuilder } from '../voxelMeshBuilder.ts';

/**
 * Books Shopfront Modeler for Townhouse C (Green Books Store).
 * Strictly complies with docs/VOXEL_GRID_SPECIFICATION.md (VOXEL_UNIT = 0.05).
 * All dimensions (w, h, d) and coordinates (x, y, z) are exact multiples of 0.05.
 */
export function buildBooksShopfront(b: VoxelMeshBuilder, isWinter: boolean): void {
  // Palettes (docs/VOXEL_GRID_SPECIFICATION.md §4)
  const cBasalt = 0x334155;    // Slate plinth, brackets, steps, metal
  const cEmerald = 0x15803d;   // Ground floor facade wall
  const cOak = 0x713f12;       // Bog oak wood trim, door, planter base
  const cDarkWood = 0x451a03;   // Dark door core / cart frame
  const cWarmGlass = 0xfef08a; // Transom & window warm evening light
  const cBrass = 0xfacc15;     // Brass doorknob & gold book accent
  const cSageTrim = 0xdcfce7;  // Shopfront frame & signboard border
  const cDarkGreen = 0x166534; // Deep pine awning stripe & garlands
  const cMint = 0x86efac;      // Mint pastel awning stripe
  const cSignBg = 0x14532d;    // Forest green signboard background
  const cLimeText = 0xa3e635;  // 3D letters 'BOOKS'
  const cPurpleBook = 0x9333ea;
  const cBlueBook = 0x2563eb;
  const cRedBook = 0xdc2626;
  const cTerracotta = 0x9a3412;
  const cFoliage = 0x16a34a;
  const cFoliageLight = 0x22c55e;
  const cBerry = 0xef4444;
  const cSnow = 0xf8fafc;

  // -------------------------------------------------------------
  // 1. Цоколь / Фундамент (2 яруса базальта 0x334155)
  // W=1.70/1.65, Y=0.05/0.15
  // -------------------------------------------------------------
  b.addBox(1.70, 0.10, 1.50, 0.00, 0.05, 0.00, cBasalt);
  b.addBox(1.65, 0.10, 1.45, 0.00, 0.15, 0.00, cBasalt);

  // -------------------------------------------------------------
  // 2. Фасад первого этажа (изумруд 0x15803d, 1.60 x 1.20 x 1.40, Y=0.80)
  // -------------------------------------------------------------
  b.addBox(1.60, 1.20, 1.40, 0.00, 0.80, 0.00, cEmerald);

  // -------------------------------------------------------------
  // 3. Входной портал (мореный дуб 0x713f12, X=-0.45)
  // Ступенька 0x334155, фрамуга с теплым светом 0xfef08a, ручка 0xfacc15
  // -------------------------------------------------------------
  // Ступенька у входа (базальт)
  b.addBox(0.45, 0.05, 0.10, -0.45, 0.20, 0.75, cBasalt);
  // Наличник входного портала (мореный дуб)
  b.addBox(0.45, 1.00, 0.05, -0.45, 0.70, 0.75, cOak);
  // Полотно двери (темное дерево с филенками)
  b.addBox(0.35, 0.65, 0.05, -0.45, 0.55, 0.75, cDarkWood);
  // Фрамуга с теплым светом над дверью (0xfef08a)
  b.addBox(0.35, 0.25, 0.05, -0.45, 1.00, 0.75, cWarmGlass);
  // Латунная ручка (0xfacc15)
  b.addBox(0.05, 0.05, 0.05, -0.30, 0.55, 0.80, cBrass);

  // -------------------------------------------------------------
  // 4. Большая книжная витрина (X=0.30)
  // Рама 0xdcfce7, теплое стекло 0xfef08a, полка с книгами
  // -------------------------------------------------------------
  // Обрамление витрины (мятный светлый наличник)
  b.addBox(0.75, 0.85, 0.05, 0.30, 0.70, 0.75, cSageTrim);
  // Подоконник витрины (дуб)
  b.addBox(0.80, 0.05, 0.10, 0.30, 0.25, 0.75, cOak);
  // Витринное стекло с теплым светом (0xfef08a)
  b.addBox(0.65, 0.75, 0.05, 0.30, 0.70, 0.75, cWarmGlass);
  // Оконный переплет (импост и горбылек)
  b.addBox(0.05, 0.75, 0.05, 0.30, 0.70, 0.80, cSageTrim);
  b.addBox(0.65, 0.05, 0.05, 0.30, 0.90, 0.80, cSageTrim);
  // Деревянная полка для книг
  b.addBox(0.60, 0.05, 0.10, 0.30, 0.40, 0.75, cOak);
  // Выкладка книг на витрине (0x9333ea, 0x2563eb, 0xdc2626, 0xfacc15)
  b.addBox(0.10, 0.15, 0.05, 0.10, 0.50, 0.75, cPurpleBook);
  b.addBox(0.10, 0.15, 0.05, 0.20, 0.50, 0.75, cBlueBook);
  b.addBox(0.10, 0.15, 0.05, 0.30, 0.50, 0.75, cRedBook);
  b.addBox(0.10, 0.15, 0.05, 0.40, 0.50, 0.75, cBrass);
  b.addBox(0.10, 0.10, 0.05, 0.50, 0.45, 0.75, cPurpleBook);

  // -------------------------------------------------------------
  // 5. Полосатая маркиза (8 наклонных полос: 0x166534 и 0x86efac)
  // -------------------------------------------------------------
  for (let i = 0; i < 8; i++) {
    const ax = -0.05 + i * 0.10;
    const col = i % 2 === 0 ? cDarkGreen : cMint;
    // Верхний наклонный ярус
    b.addBox(0.10, 0.05, 0.15, ax, 1.25, 0.80, col);
    // Нижний свес с ламбрекеном
    b.addBox(0.10, 0.10, 0.15, ax, 1.15, 0.95, col);
  }

  // -------------------------------------------------------------
  // 6. Объемная 3D-вывеска 'BOOKS' над маркизой
  // Фон 0x14532d, рамка 0xdcfce7, буквы 0xa3e635
  // -------------------------------------------------------------
  // Фон вывески
  b.addBox(0.75, 0.20, 0.05, 0.30, 1.35, 0.75, cSignBg);
  // Рамка вывески (верх, низ, боковины)
  b.addBox(0.80, 0.05, 0.05, 0.30, 1.45, 0.75, cSageTrim);
  b.addBox(0.80, 0.05, 0.05, 0.30, 1.25, 0.75, cSageTrim);
  b.addBox(0.05, 0.20, 0.05, -0.10, 1.35, 0.75, cSageTrim);
  b.addBox(0.05, 0.20, 0.05, 0.70, 1.35, 0.75, cSageTrim);
  // Буквы 'B', 'O', 'O', 'K', 'S' (0xa3e635)
  b.addBox(0.05, 0.10, 0.05, 0.10, 1.35, 0.80, cLimeText); // B
  b.addBox(0.05, 0.10, 0.05, 0.20, 1.35, 0.80, cLimeText); // O
  b.addBox(0.05, 0.10, 0.05, 0.30, 1.35, 0.80, cLimeText); // O
  b.addBox(0.05, 0.10, 0.05, 0.40, 1.35, 0.80, cLimeText); // K
  b.addBox(0.05, 0.10, 0.05, 0.50, 1.35, 0.80, cLimeText); // S

  // -------------------------------------------------------------
  // 7. Угловая консольная вертикальная вывеска (Blade sign)
  // Кронштейн 0x334155, табло 0x14532d, буквы 0xa3e635
  // -------------------------------------------------------------
  // Верхний и нижний кронштейны из кованого базальта
  b.addBox(0.15, 0.05, 0.05, -0.85, 1.30, 0.40, cBasalt);
  b.addBox(0.15, 0.05, 0.05, -0.85, 0.90, 0.40, cBasalt);
  // Вертикальное табло вывески
  b.addBox(0.05, 0.45, 0.20, -0.95, 1.10, 0.40, cSignBg);
  // Рамка табло (верх и низ)
  b.addBox(0.05, 0.05, 0.25, -0.95, 1.35, 0.40, cSageTrim);
  b.addBox(0.05, 0.05, 0.25, -0.95, 0.85, 0.40, cSageTrim);
  // Вертикальная надпись 'B-O-K-S'
  b.addBox(0.05, 0.05, 0.10, -0.95, 1.25, 0.40, cLimeText);
  b.addBox(0.05, 0.05, 0.10, -0.95, 1.15, 0.40, cLimeText);
  b.addBox(0.05, 0.05, 0.10, -0.95, 1.05, 0.40, cLimeText);
  b.addBox(0.05, 0.05, 0.10, -0.95, 0.95, 0.40, cLimeText);

  // -------------------------------------------------------------
  // 8. Уличные детали: кашпо слева, книжная тележка справа
  // -------------------------------------------------------------
  // Кашпо с зеленью слева (X=-0.70)
  b.addBox(0.15, 0.15, 0.15, -0.70, 0.25, 0.75, cOak);
  b.addBox(0.20, 0.05, 0.20, -0.70, 0.35, 0.75, cTerracotta);
  b.addBox(0.20, 0.15, 0.20, -0.70, 0.45, 0.75, cFoliage);
  b.addBox(0.10, 0.10, 0.10, -0.70, 0.55, 0.75, cFoliageLight);
  b.addBox(0.05, 0.05, 0.05, -0.65, 0.45, 0.85, cBerry);
  b.addBox(0.05, 0.05, 0.05, -0.75, 0.50, 0.85, cBerry);

  // Книжная тележка справа (X=0.65)
  // Колеса и ось
  b.addBox(0.05, 0.10, 0.10, 0.55, 0.15, 0.80, cBasalt);
  b.addBox(0.05, 0.10, 0.10, 0.75, 0.15, 0.80, cBasalt);
  b.addBox(0.20, 0.05, 0.05, 0.65, 0.15, 0.80, cBasalt);
  // Лоток тележки
  b.addBox(0.25, 0.05, 0.15, 0.65, 0.25, 0.80, cOak);
  b.addBox(0.25, 0.10, 0.05, 0.65, 0.30, 0.85, cDarkWood);
  b.addBox(0.25, 0.10, 0.05, 0.65, 0.30, 0.75, cDarkWood);
  b.addBox(0.05, 0.10, 0.15, 0.55, 0.30, 0.80, cDarkWood);
  b.addBox(0.05, 0.10, 0.15, 0.75, 0.30, 0.80, cDarkWood);
  b.addBox(0.05, 0.15, 0.05, 0.80, 0.35, 0.80, cBasalt); // ручка
  // Книги в тележке
  b.addBox(0.05, 0.10, 0.10, 0.60, 0.35, 0.80, cRedBook);
  b.addBox(0.05, 0.10, 0.10, 0.65, 0.35, 0.80, cBlueBook);
  b.addBox(0.05, 0.10, 0.10, 0.70, 0.35, 0.80, cBrass);

  // -------------------------------------------------------------
  // 9. Зимний слой (isWinter: boolean)
  // Шапки снега на маркизе, вывеске и тележке; хвойная гирлянда с ягодами
  // -------------------------------------------------------------
  if (isWinter) {
    // Снег на маркизе (два яруса)
    b.addBox(0.80, 0.05, 0.15, 0.30, 1.30, 0.80, cSnow);
    b.addBox(0.80, 0.05, 0.15, 0.30, 1.20, 0.95, cSnow);

    // Снег на вывеске 'BOOKS'
    b.addBox(0.80, 0.05, 0.10, 0.30, 1.50, 0.75, cSnow);

    // Снег на консольной вывеске
    b.addBox(0.05, 0.05, 0.25, -0.95, 1.40, 0.40, cSnow);

    // Снег на уличных деталях: тележка, кашпо, ступенька
    b.addBox(0.20, 0.05, 0.10, 0.65, 0.40, 0.80, cSnow);
    b.addBox(0.15, 0.05, 0.15, -0.70, 0.60, 0.75, cSnow);
    b.addBox(0.45, 0.05, 0.05, -0.45, 0.25, 0.80, cSnow);

    // Праздничная хвойная гирлянда над дверью
    b.addBox(0.45, 0.05, 0.05, -0.45, 1.20, 0.80, cDarkGreen);
    b.addBox(0.05, 0.05, 0.05, -0.65, 1.20, 0.85, cBerry);
    b.addBox(0.05, 0.05, 0.05, -0.25, 1.20, 0.85, cBerry);

    // Рождественский венок на двери с ягодой
    b.addBox(0.15, 0.15, 0.05, -0.45, 0.75, 0.80, cDarkGreen);
    b.addBox(0.05, 0.05, 0.05, -0.45, 0.75, 0.85, cBerry);

    // Боковая гирлянда на левом фасаде
    b.addBox(0.05, 0.05, 0.60, -0.85, 1.40, 0.20, cDarkGreen);
    b.addBox(0.05, 0.05, 0.05, -0.85, 1.40, 0.00, cBerry);
    b.addBox(0.05, 0.05, 0.05, -0.85, 1.40, 0.40, cBerry);
  }
}
