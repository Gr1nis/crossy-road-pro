import { VoxelMeshBuilder } from '../voxelMeshBuilder.ts';

/**
 * Books Roof & Chimney Modeler for Townhouse C (Green Books Store).
 * Strictly complies with docs/VOXEL_GRID_SPECIFICATION.md (VOXEL_UNIT = 0.05).
 * All dimensions (w, h, d) and coordinates (x, y, z) are exact multiples of 0.05.
 */
export function buildBooksRoof(b: VoxelMeshBuilder, isWinter: boolean): void {
  // Palettes (docs/VOXEL_GRID_SPECIFICATION.md §4)
  const cTileLight = 0xc2410c;    // Терракотовая черепица (светлый ярус / оголовки)
  const cTileDark = 0x9a3412;     // Темная обожженная терракота
  const cRidge = 0x7c2d12;        // Коньковая черепица (Y=3.85)
  const cDormerWall = 0x15803d;   // Изумрудные стенки люкарны
  const cGlass = 0xfef08a;        // Теплый вечерний свет внутри люкарны
  const cSill = 0xdcfce7;         // Известняковый подоконник люкарны
  const cChimneyBrick = 0x854d0e; // Обожженный кирпич дымохода
  const cCollar = 0x334155;       // Базальтовый каменный воротник
  const cSnow = 0xf8fafc;         // Чистый снежный покров
  const cSmoke = 0xe2e8f0;        // Клубящийся дым из трубы

  // =========================================================================
  // 1. Двускатная терракотовая крыша: 5 ступенчатых ярусов черепицы
  // Свесы по X=1.70 (симметрично над стенами W=1.60 и карнизом W=1.70).
  // Ступени по Z: 1.50 -> 1.20 -> 0.90 -> 0.60 -> 0.30 (шаг ската 0.15 = 3 вокселя).
  // Стыковка по Y: 2.80 -> 3.00 -> 3.20 -> 3.50 -> 3.80 -> 3.90 (конек Y=3.85).
  // =========================================================================
  b.addBox(1.70, 0.20, 1.50, 0.00, 2.90, 0.00, cTileLight); // Ярус 1 (Y: 2.80 - 3.00)
  b.addBox(1.70, 0.20, 1.20, 0.00, 3.10, 0.00, cTileDark);  // Ярус 2 (Y: 3.00 - 3.20)
  b.addBox(1.70, 0.30, 0.90, 0.00, 3.35, 0.00, cTileLight); // Ярус 3 (Y: 3.20 - 3.50)
  b.addBox(1.70, 0.30, 0.60, 0.00, 3.65, 0.00, cTileDark);  // Ярус 4 (Y: 3.50 - 3.80)
  b.addBox(1.70, 0.10, 0.30, 0.00, 3.85, 0.00, cRidge);     // Ярус 5: Коньковая черепица (Y=3.85, span 3.80 - 3.90)

  // =========================================================================
  // 2. Фронтонная люкарна (Dormer window) на переднем скате крыши (X = -0.35)
  // Балансирует фасад напротив дымохода (X = +0.45, Z = -0.25).
  // =========================================================================
  const dormerX = -0.35;
  // Стенки люкарны (изумрудный фасадный цвет)
  b.addBox(0.30, 0.25, 0.25, dormerX, 3.30, 0.55, cDormerWall);
  // Окно люкарны с теплым светом
  b.addBox(0.20, 0.20, 0.05, dormerX, 3.30, 0.70, cGlass);
  // Выступающий подоконник (известняк / светлый камень)
  b.addBox(0.25, 0.05, 0.05, dormerX, 3.15, 0.70, cSill);
  // Скатная крыша люкарны (терракота)
  b.addBox(0.35, 0.10, 0.30, dormerX, 3.50, 0.55, cTileLight);

  // =========================================================================
  // 3. Кирпичный дымоход: шахта (0.45, 3.85, -0.25), воротник и 2 оголовка
  // =========================================================================
  const chimX = 0.45;
  const chimZ = -0.25;

  // Шахта из кирпича (Y: 3.50 - 4.20)
  b.addBox(0.25, 0.70, 0.25, chimX, 3.85, chimZ, cChimneyBrick);
  // Базальтовый каменный воротник (Y: 4.20 - 4.30)
  b.addBox(0.30, 0.10, 0.30, chimX, 4.25, chimZ, cCollar);
  // 2 терракотовые трубы / оголовка на Y=4.35 (Y: 4.30 - 4.40)
  b.addBox(0.10, 0.10, 0.10, chimX - 0.05, 4.35, chimZ, cTileLight); // Левая труба (X = 0.40)
  b.addBox(0.10, 0.10, 0.10, chimX + 0.05, 4.35, chimZ, cTileLight); // Правая труба (X = 0.50)

  // =========================================================================
  // 4. Зимний слой (isWinter)
  // Снежные шапки на коньке, скатах, люкарне, воротнике и 4 клуба дыма.
  // =========================================================================
  if (isWinter) {
    // Снежная шапка вдоль конька крыши
    b.addBox(1.70, 0.05, 0.25, 0.00, 3.95, 0.00, cSnow);

    // Снежный покров на ступенчатых скатах (передний и задний)
    b.addBox(1.40, 0.05, 0.20, 0.00, 3.55, 0.40, cSnow);  // Передний верхний скат
    b.addBox(1.40, 0.05, 0.20, 0.00, 3.55, -0.40, cSnow); // Задний верхний скат
    b.addBox(1.50, 0.05, 0.15, 0.00, 3.25, 0.55, cSnow);  // Передний нижний скат
    b.addBox(1.50, 0.05, 0.15, 0.00, 3.25, -0.55, cSnow); // Задний нижний скат

    // Снег на крыше люкарны
    b.addBox(0.35, 0.05, 0.30, dormerX, 3.60, 0.55, cSnow);

    // Снег на воротнике дымохода
    b.addBox(0.30, 0.05, 0.30, chimX, 4.30, chimZ, cSnow);

    // 4 клубящихся воксельных шарика дыма со смещением по ветру
    b.addBox(0.10, 0.10, 0.10, chimX, 4.50, chimZ, cSmoke);
    b.addBox(0.10, 0.10, 0.10, chimX - 0.05, 4.65, chimZ + 0.05, cSmoke);
    b.addBox(0.10, 0.10, 0.10, chimX, 4.80, chimZ + 0.10, cSmoke);
    b.addBox(0.05, 0.05, 0.05, chimX - 0.05, 4.90, chimZ + 0.15, cSmoke);
  }
}
